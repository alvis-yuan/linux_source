uint32_t ReadWordSet_ASC(CharBuffer *cbuf, uint8_t code)
{
	uint32_t i, rc;

	switch (Settings.ASC_WordSet) {
	case 1:  rc = ReadWordSet_ASCII_9x17(cbuf->Data, code);  cbuf->Top = 7; break;
	default: rc = ReadWordSet_ASCII_12x24(cbuf->Data, code); cbuf->Top = 0; break;
	}

	if (Settings.EmphasizedMode[CHAR_TYPE_ASC]) {
		for (i = 0; i < MAX_CHAR_HEIGHT; i++)
			cbuf->Data[i] = Emphasized_Conv(cbuf->Data[i]);
	}

	return rc;
}

uint32_t ReadWordSet_CodePage(CharBuffer *cbuf, uint8_t code)
{
	uint32_t i, offset, rc, address;

	if (Settings.CodePage > 63)
		return 0;
	offset = CODE_PAGE_MAPPINGS[Settings.CodePage];
	if (offset == 255)
		return 0;

	switch (Settings.ASC_WordSet) {
	case 1:
		address = (offset * 2560 + 0x311A0) + (code - 0x80) * 20;
		rc = GetFontData_9x17(cbuf->Data, address);
		cbuf->Top = 7;
		break;
	default:
		address = (offset * 4608 + 0x2A30) + (code - 0x80) * 36;
		rc = GetFontData_12x24(cbuf->Data, address);
		cbuf->Top = 0;
		break;
	}

	if (Settings.EmphasizedMode[CHAR_TYPE_ASC]) {
		for (i = 0; i < MAX_CHAR_HEIGHT; i++)
			cbuf->Data[i] = Emphasized_Conv(cbuf->Data[i]);
	}

	return rc;
}

uint32_t ReadWordSet_Unicode(CharBuffer *cbuf, uint32_t unicode)
{
	uint32_t i, rc, address;

	if (unicode < 0x20)
		return 0;

	if (unicode < 0x80) {
		switch (Settings.ASC_WordSet) {
		case 1:
			cbuf->AdvanceX = 9;
			cbuf->Top = 7;
			cbuf->CharType = CHAR_TYPE_ASC;
			rc = ReadWordSet_ASCII_9x17(cbuf->Data, unicode);
			break;
		default:
			cbuf->AdvanceX = 12;
			cbuf->Top = 0;
			cbuf->CharType = CHAR_TYPE_ASC;
			rc = ReadWordSet_ASCII_12x24(cbuf->Data, unicode);
		}
		goto _exit;
	}

	for (i = 0; i < uff_header->num_charmaps; i++) {
		if (unicode < uff_charmaps[i].start)
			return 0;
		if (unicode > uff_charmaps[i].end)
			continue;
		cbuf->CharType = CHAR_TYPE_CJK;
		address = 0x80000 + uff_charmaps[i].offset + (unicode - uff_charmaps[i].start) * uff_charmaps[i].pitch;
		rc = GetFontData_Dyn(cbuf, address, unicode, &uff_charmaps[i]);
		break;
	}
	if (i == uff_header->num_charmaps)
		return 0;

_exit:
	if (Settings.EmphasizedMode[cbuf->CharType]) {
		for (i = 0; i < MAX_CHAR_HEIGHT; i++)
			cbuf->Data[i] = Emphasized_Conv(cbuf->Data[i]);
	}

	return rc;
}

uint32_t MBCS_to_Unicode(uint8_t *bytes, uint32_t subsequent_bytes)
{
	uint32_t unicode;

	switch (Settings.CJK_WordSet) {
	case CJK_WORDSET_BIG5:
		unicode = BIG5_to_Unicode(bytes, subsequent_bytes);
		break;
	case CJK_WORDSET_SHIFT_JIS:
		unicode = Shift_JIS_to_Unicode(bytes, subsequent_bytes);
		break;
	case CJK_WORDSET_JIS0208:
		unicode = JIS0208_to_Unicode(bytes, subsequent_bytes);
		break;
	case CJK_WORDSET_KSC5601:
		unicode = KSC5601_to_Unicode(bytes, subsequent_bytes);
		break;
	default:
		unicode = GB18030_to_Unicode(bytes, subsequent_bytes);
		break;
	}
	return unicode;
}

/*
 *         +--------+--------+--------+--------+
 * 1-byte: |        |        |        |0xxxxxxx|
 *         +--------+--------+--------+--------+
 *         +--------+--------+--------+--------+
 * 2-byte: |        |        |110xxxxx|10xxxxxx|
 *         +--------+--------+--------+--------+
 *         +--------+--------+--------+--------+
 * 3-byte: |        |1110xxxx|10xxxxxx|10xxxxxx|
 *         +--------+--------+--------+--------+
 *         +--------+--------+--------+--------+
 * 4-byte: |11110xxx|10xxxxxx|10xxxxxx|10xxxxxx|
 *         +--------+--------+--------+--------+
 */
uint32_t Utf8_to_Unicode(uint8_t *bytes, uint32_t subsequent_bytes)
{
	uint32_t i, unicode, explen;

	unicode = bytes[0];

	if ((bytes[0] & 0x80) == 0x00) {
		explen = 1;
		unicode &= 0x7F;
	}
	else if ((bytes[0] & 0xE0) == 0xC0) {
		explen = 2;
		unicode &= 0x1F;
	}
	else if ((bytes[0] & 0xF0) == 0xE0) {
		explen = 3;
		unicode &= 0x0F;
	}
	else if ((bytes[0] & 0xF8) == 0xF0) {
		explen = 4;
		unicode &= 0x07;
	}
	else
		return 0;

	if (subsequent_bytes + 1 < explen)
		return explen;

	for (i = 1; i < explen; i++) {
		if ((bytes[i] & 0xC0) != 0x80)
			return 0;
		unicode <<= 6;
		unicode |= (bytes[i] & 0x3F);
	}

	return unicode;
}

int WordSetInit(void)
{
	const char *filename = "/data/PUB/country_font_storage.bin";
	struct stat stbuf;
	FILE *fp;

	if (stat(filename, &stbuf) != 0)
		return -1;
	if (stbuf.st_size < 0x80020 + sizeof(uff_header_t))
		return -1;

	fontData = (uint8_t *)malloc(stbuf.st_size);
	if (!fontData)
		return -1;

	fp = fopen(filename, "rb");
	if (fp == NULL)
		return -1;

	/* Font version */
	fread(fontVersion, 1, 16, fp);
	/* Font language */
	fread(fontLanguage, 1, 16, fp);
	/* Font data */
	fread(fontData, 1, stbuf.st_size - 32, fp);

	fclose(fp);

	uff_header = (uff_header_t *)(fontData + 0x80000);
	uff_charmaps = (uff_charmap_t *)(fontData + 0x80000 + uff_header->charmap_offset);

	return 0;
}
